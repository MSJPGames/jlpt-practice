#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""音声合成にかける台本の「読みが割れる語」を洗い出す。
聴解の台本を作ったら必ずこれを通す。使い方:

    python3 yomi.py out_M1.json          # script の text を見る
    python3 yomi.py out_M1.json --all    # situation / choices も見る

見つかったものは、かな書きにするか、別の言い方に変えること。
"""
import json, sys, re

# (見つける形, どう読み違えられるか, 直し方の例)
RULES = [
    (r'十分', 'じゅっぷん／じゅうぶん', '「じゅっぷん」か「足ります」に'),
    (r'一日', 'ついたち／いちにち', '「いちにち」とかな書き'),
    (r'十日', 'とおか／じゅうにち', '「とおか」とかな書き'),
    (r'二十日', 'はつか／にじゅうにち', '「はつか」とかな書き'),
    (r'[一二三四五六七八九十百]+人分|人数分|\d+人分', 'ぶん／ふん', '「〜人のぶん」に'),
    (r'(?<![時十])分(?![かけっ])', 'ぶん／ふん', 'かな書きにするか言い換え'),
    (r'明後日', 'あさって／みょうごにち', '「あさって」とかな書き'),
    (r'明日', 'あす／あした／みょうにち', '「あす」に統一するかかな書き'),
    (r'一昨日', 'おととい／いっさくじつ', 'かな書き'),
    (r'一人', 'ひとり／いちにん', '「ひとり」とかな書き'),
    (r'二人', 'ふたり／ににん', '「ふたり」とかな書き'),
    (r'七[つ人時日回本枚]|九[つ人時日回本枚]', 'しち／なな、く／きゅう', 'かな書き'),
    (r'一本|六本|八本|十本|一足|六足|八足', '促音・半濁音がくずれやすい', 'かな書き'),
    (r'柄', 'がら／え', '「もよう」に'),
    (r'面', 'めん／おも／つら', '「高さ」「表面」など別の語に'),
    (r'札', 'ふだ／さつ', '「ふだ」とかな書き'),
    (r'粉', 'こな／ふん', '「こな」とかな書き'),
    (r'生地', 'きじ／なまじ', '「きじ」とかな書き'),
    (r'空く', 'あく／すく', '「あく」とかな書き'),
    (r'行った', 'いった／おこなった', '「出かけた」「おこなった」に'),
    (r'代わり|変わり', 'かわり', '同音。意味が取れるか確かめる'),
    (r'録れる|撮れる', '当て字。読み違いが多い', '「録音できる」「写真が撮れる」に'),
    (r'大人数|少人数', 'だいにんずう／おおにんずう', 'かな書き'),
    (r'市場', 'いちば／しじょう', 'どちらか決めてかな書き'),
    (r'牧場', 'まきば／ぼくじょう', 'かな書き'),
    (r'最中', 'さいちゅう／もなか', '「〜しているところ」に'),
]
# よく使う語で、上の広すぎる規則にかかるが直さなくてよいもの
SKIP = re.compile(r'^(方法|方向|一方|方針|両方|夕方|地方|時間|人間|期間|週間|年間|昼間|世間'
                  r'|物件|荷物|品物|建物|食べ物|飲み物|着物|果物|物語|買い物|忘れ物'
                  r'|目的|注目|目次|項目|目標|科目|種目|目安|目印'
                  r'|下記|以下|下旬|地下|部下|下水|廊下|靴下|階下'
                  r'|上手|以上|屋上|上旬|向上|上司|売上|水上|海上'
                  r'|入学|入口|入院|記入|購入|輸入|収入|入場'
                  r'|開始|開催|公開|開発|展開|再開'
                  r'|表示|発表|代表|表現|表情|時間表)')


def scan(path, allfields=False):
    data = json.load(open(path, encoding='utf-8'))
    hits = []
    for q in data:
        texts = [s['text'] for s in q.get('script', [])]
        if allfields:
            texts += [q.get('situation', ''), q.get('question', '')] + list(q.get('choices', []))
        for t in texts:
            for pat, why, how in RULES:
                for m in re.finditer(pat, t):
                    a, b = max(0, m.start() - 6), min(len(t), m.end() + 6)
                    ctx = t[a:b]
                    if SKIP.match(t[m.start():m.start() + 4]):
                        continue
                    hits.append((q.get('id', '?'), m.group(0), why, how, ctx))
    seen, out = set(), []
    for h in hits:
        k = (h[0], h[1], h[4])
        if k not in seen:
            seen.add(k)
            out.append(h)
    return out


if __name__ == '__main__':
    res = scan(sys.argv[1], '--all' in sys.argv)
    cur = None
    for i, w, why, how, ctx in res:
        if i != cur:
            print(f'\n== {i}')
            cur = i
        print(f'  「{w}」（{why}）… {how}\n      …{ctx}…')
    print(f'\n合計 {len(res)} か所')
